/**
 * build-world-map.mjs
 *
 * Precomputes the admin visitor map's world silhouette so no geo library ships
 * to the browser. Reads the world-atlas TopoJSON (a devDependency), projects it
 * equirectangular into a fixed viewBox, rounds coordinates, and writes a single
 * merged path string to src/components/admin/worldPath.ts.
 *
 * Re-run only if you want different geometry:
 *   node scripts/build-world-map.mjs
 *
 * The equirectangular projection here MUST stay in sync with project() in
 * src/components/admin/VisitorMap.tsx — that is what puts the dots in the right
 * place on top of this path.
 */

import * as fs from "fs";
import * as path from "path";

import { feature } from "topojson-client";

const WIDTH = 1000;
const HEIGHT = 500;
// Antarctica is a lot of path data for a visitor map; clip the deep south.
const MIN_LAT = -60;
const MAX_LAT = 84;
// The map renders ~800px wide at most, so integer coordinates at this viewBox
// are already sub-pixel. Dropping repeated points after rounding cuts the path
// data by more than half with no visible difference.
const PRECISION = 0;
const MIN_RING_POINTS = 4;

const topo = JSON.parse(
  fs.readFileSync(path.resolve("node_modules/world-atlas/countries-110m.json"), "utf8")
);
const geo = feature(topo, topo.objects.countries);

function project([lon, lat]) {
  const x = ((lon + 180) / 360) * WIDTH;
  const y = ((MAX_LAT - lat) / (MAX_LAT - MIN_LAT)) * HEIGHT;
  return [x.toFixed(PRECISION), y.toFixed(PRECISION)];
}

function ringToPath(ring) {
  // Antarctica and other rings entirely south of the clip never render.
  if (ring.every(([, lat]) => lat < MIN_LAT)) return "";

  // A ring that crosses the antimeridian (Russia, Fiji) has consecutive points
  // at x≈WIDTH and x≈0. Joining those draws a stray line straight across the
  // map, so split the ring into separate subpaths at each wrap instead.
  const segments = [];
  let current = [];
  let prevKey = null;
  let prevX = null;
  for (const coord of ring) {
    const [x, y] = project(coord);
    const nx = Number(x);
    if (prevX !== null && Math.abs(nx - prevX) > WIDTH / 2) {
      segments.push(current);
      current = [];
      prevKey = null;
    }
    const key = `${x},${y}`;
    if (key !== prevKey) {
      current.push(key);
      prevKey = key;
    }
    prevX = nx;
  }
  segments.push(current);

  return segments
    .filter((points) => points.length >= MIN_RING_POINTS)
    .map((points) => `M${points.join("L")}Z`)
    .join("");
}

function polygonToPath(coordinates) {
  return coordinates.map(ringToPath).join("");
}

const paths = [];
for (const country of geo.features) {
  const { type, coordinates } = country.geometry;
  if (type === "Polygon") paths.push(polygonToPath(coordinates));
  else if (type === "MultiPolygon") paths.push(coordinates.map(polygonToPath).join(""));
}

const d = paths.join("");
const out = `// GENERATED by scripts/build-world-map.mjs — do not edit by hand.
// Equirectangular world silhouette, viewBox 0 0 ${WIDTH} ${HEIGHT},
// latitudes clipped to ${MIN_LAT}..${MAX_LAT}. Keep project() in VisitorMap.tsx in sync.

export const WORLD_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;
export const WORLD_LAT_RANGE = { min: ${MIN_LAT}, max: ${MAX_LAT} } as const;
export const WORLD_PATH =
  "${d}";
`;

const target = path.resolve("src/components/admin/worldPath.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(
  `wrote ${target} — ${geo.features.length} countries, ${(d.length / 1024).toFixed(1)} KB of path data`
);
